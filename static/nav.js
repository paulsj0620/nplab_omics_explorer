/* Shared click / keyboard / drag selection. Existing buttons and links own navigation. */
(function (global) {
  'use strict';
  function attach(nav, env = global) {
    if (nav.dataset.omicsNav === 'ready') return;
    nav.dataset.omicsNav = 'ready';
    const doc = nav.ownerDocument;
    const pill = doc.createElement('span'), preview = doc.createElement('span');
    for (const [node, cls] of [[pill, 'nav-selection-indicator'], [preview, 'nav-drag-indicator']]) {
      node.className = cls; node.setAttribute('aria-hidden', 'true'); node.dataset.navDecoration = 'true';
      nav.append(node);
    }
    preview.hidden = true;
    let gesture = null, frame = null, pending = null, timer = null, suppressUntil = 0;
    const reduced = () => env.matchMedia('(prefers-reduced-motion: reduce)').matches;
    const items = () => [...nav.children].filter(e => ['A','BUTTON'].includes(e.tagName) && !e.hidden && !e.disabled && e.getAttribute('aria-disabled') !== 'true' && e.getClientRects().length && env.getComputedStyle(e).visibility !== 'hidden');
    const active = () => items().find(e => e.matches('.active,[aria-pressed="true"],[aria-selected="true"],[aria-current="page"]') || e.querySelector('.active'));
    const itemAt = target => items().find(e => e === target || e.contains(target));
    function geometry(node, element) {
      const r = element.getBoundingClientRect(), n = nav.getBoundingClientRect();
      Object.assign(node.style, {left: `${r.left-n.left-nav.clientLeft+nav.scrollLeft}px`, top: `${r.top-n.top-nav.clientTop+nav.scrollTop}px`, width: `${r.width}px`, height: `${r.height}px`});
    }
    function sync(initial = false) {
      const selected = pending || active();
      pill.hidden = !selected || !!gesture?.dragging;
      nav.classList.toggle('nav-has-selection', !!selected);
      if (!selected) return;
      if (initial) pill.style.transition = 'none';
      geometry(pill, selected);
      if (initial) env.requestAnimationFrame(() => env.requestAnimationFrame(() => { pill.style.transition = ''; }));
    }
    function schedule() {
      if (frame !== null) return;
      frame = env.requestAnimationFrame(() => { frame = null; sync(); });
    }
    function candidate(x, y) {
      const n = nav.getBoundingClientRect();
      if (x < n.left || x > n.right || y < n.top-16 || y > n.bottom+16) return null;
      let best = null, distance = Infinity;
      for (const e of items()) {
        const r = e.getBoundingClientRect();
        const dx = Math.max(r.left-x, 0, x-r.right), dy = Math.max(r.top-y, 0, y-r.bottom);
        const d = dx*dx + dy*dy;
        if (d < distance) { distance = d; best = e; }
      }
      return best;
    }
    function resetGesture(blockClick) {
      const previous = gesture;
      gesture = null;
      preview.hidden = true;
      nav.classList.remove('nav-dragging');
      if (blockClick && previous?.dragging) suppressUntil = Date.now()+700;
      if (previous && nav.hasPointerCapture?.(previous.id)) nav.releasePointerCapture(previous.id);
      sync();
    }
    nav.addEventListener('pointerdown', e => {
      suppressUntil = 0; // A new press cannot be the click generated by the previous drag.
      if (!e.isPrimary || e.button !== 0 || e.ctrlKey || e.metaKey || e.altKey || e.shiftKey || !itemAt(e.target)) return;
      gesture = {id:e.pointerId, x:e.clientX, y:e.clientY, dragging:false};
    });
    nav.addEventListener('pointermove', e => {
      if (!gesture || e.pointerId !== gesture.id) return;
      if (!gesture.dragging && Math.hypot(e.clientX-gesture.x, e.clientY-gesture.y) < 6) return;
      if (!gesture.dragging) {
        gesture.dragging = true;
        nav.setPointerCapture(e.pointerId);
        nav.classList.add('nav-dragging');
      }
      e.preventDefault();
      const target = candidate(e.clientX,e.clientY);
      pill.hidden = true;
      preview.hidden = !target;
      if (target) {
        const r = target.getBoundingClientRect(), n = nav.getBoundingClientRect();
        Object.assign(preview.style, {width:`${r.width}px`,height:`${r.height}px`,left:`${e.clientX-n.left-nav.clientLeft-r.width/2}px`,top:`${e.clientY-n.top-nav.clientTop-r.height/2}px`});
      }
    });
    nav.addEventListener('pointerup', e => {
      if (!gesture || e.pointerId !== gesture.id) return;
      const wasDrag = gesture.dragging, target = wasDrag ? candidate(e.clientX,e.clientY) : null;
      resetGesture(wasDrag);
      if (target) target.click();
    });
    nav.addEventListener('pointercancel', () => resetGesture(true));
    nav.addEventListener('lostpointercapture', () => { if (gesture) resetGesture(true); });
    nav.addEventListener('dragstart', e => { if (gesture) e.preventDefault(); });
    nav.addEventListener('click', e => {
      if (Date.now() < suppressUntil && e.isTrusted && e.detail > 0) { e.preventDefault(); e.stopImmediatePropagation(); suppressUntil = 0; }
    }, true);
    nav.addEventListener('click', e => {
      const selected = itemAt(e.target);
      if (!selected || e.defaultPrevented) return;
      if (selected.tagName === 'A' && !e.ctrlKey && !e.metaKey && !e.altKey && !e.shiftKey && e.button === 0 && !selected.hasAttribute('download') && (!selected.target || selected.target === '_self')) {
        const destination = new URL(selected.href, env.location.href);
        if (destination.origin !== env.location.origin || !['http:','https:'].includes(destination.protocol)) return;
        // Give the selected pill its transition before following the original URL.
        e.preventDefault();
        if (pending) pending.classList.remove('nav-target');
        pending = selected;
        selected.classList.add('nav-target');
        nav.classList.add('nav-pending');
        sync();
        env.clearTimeout(timer);
        timer = env.setTimeout(() => env.location.assign(destination.href), reduced() ? 0 : 260);
      } else {
        schedule(); // The existing button handler has already updated its state.
      }
    });
    doc.addEventListener('keydown', e => { if (e.key === 'Escape') resetGesture(true); });
    env.addEventListener('blur', () => resetGesture(true));
    env.addEventListener('resize', () => { resetGesture(true); schedule(); });
    env.addEventListener('languagechange', schedule);
    env.addEventListener('pageshow', () => {
      if (pending) pending.classList.remove('nav-target');
      pending = null; nav.classList.remove('nav-pending'); sync(true);
    });
    nav.addEventListener('scroll', schedule);
    const resize = new env.ResizeObserver(schedule);
    const observed = new Set();
    const observeItems = () => items().forEach(e => { if (!observed.has(e)) { observed.add(e); resize.observe(e); } });
    resize.observe(nav); observeItems();
    const mutation = new env.MutationObserver(records => {
      if (records.every(r => r.target.dataset?.navDecoration || (r.type === 'childList' && [...r.addedNodes,...r.removedNodes].every(n => n.dataset?.navDecoration)))) return;
      observeItems(); schedule();
    });
    mutation.observe(nav, {subtree:true,childList:true,attributes:true,attributeFilter:['class','style','hidden','disabled','aria-pressed','aria-selected','aria-current','aria-disabled']});
    nav.classList.add('omics-drag-nav');
    sync(true);
    return {sync,cancel:() => resetGesture(true)};
  }
  function start() {
    const scan = () => global.document.querySelectorAll('[data-drag-nav],.menu_item_box').forEach(nav => attach(nav));
    scan();
    // Vendor navigation is inserted by its own DOM-ready handler.
    const host = global.document.getElementById('mainNav');
    if (host && !host.querySelector('.menu_item_box')) {
      const observer = new global.MutationObserver(() => { scan(); if (host.querySelector('.menu_item_box')) observer.disconnect(); });
      observer.observe(host,{childList:true,subtree:true});
    }
  }
  if (typeof module !== 'undefined' && module.exports) module.exports = {attach};
  if (global.document) {
    global.OmicsNav = {attach};
    if (global.document.readyState === 'loading') global.document.addEventListener('DOMContentLoaded',start,{once:true});
    else start();
  }
})(typeof window !== 'undefined' ? window : globalThis);
